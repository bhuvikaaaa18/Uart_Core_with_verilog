module Baud_Rate_Generator_tb;

    reg clk;
    reg reset;
    reg [2:0] baud_sel;

    wire baud_tick;
    wire sample_tick;

    //----------------------------------------------------------
    // DUT
    //----------------------------------------------------------

    Baud_Rate_Generator #(
        .CLK_FREQ(100_000_000),
        .OVERSAMPLE(16)
    ) UUT (
        .clk(clk),
        .reset(reset),
        .baud_sel(baud_sel),
        .baud_tick(baud_tick),
        .sample_tick(sample_tick)
    );

    //----------------------------------------------------------
    // 100 MHz Clock (10 ns period)
    //----------------------------------------------------------

    initial begin
        clk = 1'b0;
        forever #5 clk = ~clk;
    end

    //----------------------------------------------------------
    // Stimulus
    //----------------------------------------------------------

    initial begin

        reset    = 1'b1;
        baud_sel = 3'd0;

        #20;
        reset = 1'b0;

        //==========================
        // 9600 baud
        //==========================
        baud_sel = 3'd0;
        #300000;      // 300 us

        //==========================
        // 19200 baud
        //==========================
        baud_sel = 3'd1;
        #180000;      // 180 us

        //==========================
        // 38400 baud
        //==========================
        baud_sel = 3'd2;
        #100000;      // 100 us

        //==========================
        // 57600 baud
        //==========================
        baud_sel = 3'd3;
        #70000;       // 70 us

        //==========================
        // 115200 baud
        //==========================
        baud_sel = 3'd4;
        #40000;       // 40 us

        //==========================
        // 230400 baud
        //==========================
        baud_sel = 3'd5;
        #20000;       // 20 us

        //==========================
        // 460800 baud
        //==========================
        baud_sel = 3'd6;
        #10000;       // 10 us

        //==========================
        // 921600 baud
        //==========================
        baud_sel = 3'd7;
        #5000;        // 5 us

        $finish;

    end

endmodule